package com.flowset.planner.projects.controller;

import com.flowset.planner.projects.dto.ProjectActivityResponse;
import com.flowset.planner.projects.service.ProjectActivityService;
import com.flowset.shared.dto.PageResponse;
import io.swagger.v3.oas.annotations.Operation;
import io.swagger.v3.oas.annotations.security.SecurityRequirement;
import io.swagger.v3.oas.annotations.tags.Tag;
import java.util.UUID;
import org.springframework.security.access.prepost.PreAuthorize;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

@RestController
@RequestMapping("/api/v1/projects/{projectId}/activity")
@Tag(name = "Project Activity", description = "Immutable timeline generated by project actions")
@SecurityRequirement(name = "bearerAuth")
public class ProjectActivityController {

    private final ProjectActivityService activityService;

    public ProjectActivityController(ProjectActivityService activityService) {
        this.activityService = activityService;
    }

    @GetMapping
    @PreAuthorize("hasAnyRole('PLANNER','ADMIN')")
    @Operation(summary = "List project activity (newest first)")
    public PageResponse<ProjectActivityResponse> list(
            @PathVariable UUID projectId,
            @RequestParam(defaultValue = "0") int page,
            @RequestParam(defaultValue = "30") int size
    ) {
        return activityService.list(projectId, page, size);
    }
}
